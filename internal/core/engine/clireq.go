// cliRecreate creates a fresh chat for a conversation and switches the
// conversation to it, as v0.1.20's RecreateControlChat and
// RecreateSessionChat did: the old chat gets a link to the new one (with
// an @mention), the new one an @mention and its ready message. The
// conversation, its Codex session and its pending replies stay; what is
// still to be sent goes to the new chat. The old chat is not deleted and
// is no longer read.
func (e *Engine) cliRecreate(ctx context.Context, r CLIRequest, p *cliProgress, control bool) (CLIResult, error) {
	if p.Stage == "" {
		var cs *convState
		if control {
			cs = e.conv(e.controlID)
			if cs == nil {
				return cliFail("Teams control chat not found")
			}
		} else {
			var msg string
			if cs, msg = e.cliSession(r.Selector); cs == nil {
				return cliFail("%s", msg)
			}
		}
		e.mu.Lock()
		id, label, state, chat, title, thread := cs.id, cs.label, cs.state, cs.chat, cs.title, cs.threadID
		e.mu.Unlock()
		if !control {
			switch state {
			case store.ConvActive, store.ConvParked:
			case store.ConvHold:
				if !r.Activate {
					return cliFail("Teams session %s is held; rerun with --activate to recreate and reactivate it", label)
				}
			default:
				return cliFail("Teams session %s has status %q and cannot be recreated", label, state)
			}
			if r.History {
				if _, ok := e.cliSource(id, thread); !ok {
					return cliFail("local Codex transcript not found for session %s", label)
				}
				if _, running := e.importJobOf(id); running {
					return cliFail("a history import is still running for session %s; wait for `Import complete` and retry", label)
				}
			}
		} else if chat == "" {
			return cliFail("the Teams control chat is still being created; retry when it is ready")
		}
		if strings.TrimSpace(title) == "" {
			title = label
			if control {
				title = e.controlTitle()
			}
		}
		p.Conv, p.Old, p.Title = id, chat, title
	}
	cs := e.conv(p.Conv)
	if cs == nil {
		return cliFail("Teams session not found for %q", r.Selector)
	}
	e.mu.Lock()
	label, cwd := cs.label, cs.cwd
	e.mu.Unlock()
	if p.Chat == "" {
		info, res, err := e.cliCreateChat(ctx, p.Title, fmt.Sprintf("recreate-%s-%d-%s", e.prefix, p.Conv, r.ID))
		if err != nil || res != nil {
			return derefResult(res), err
		}
		p.Chat, p.URL, p.Stage = info.ID, info.URL, cliCreated
		if err := e.update(func(tx *store.Tx) error { return e.saveCLI(tx, r.ID, p) }); err != nil {
			return CLIResult{}, err
		}
	}
	if p.Stage == cliCreated {
		var msgs []store.OutMsg
		if p.Old != "" && p.Old != p.Chat {
			kind, session := "Control chat", ""
			if !control {
				kind, session = "Work chat", label
			}
			var err error
			msgs, err = e.render(ctx, channel.RichDoc{Label: labelHelper, Markdown: textChatMoved(kind, session, p.URL), Mention: true},
				store.OutNotice, cliKey(r.ID, "moved"))
			if err != nil {
				return CLIResult{}, err
			}
		}
		p.Stage = cliMoving
		err := e.update(func(tx *store.Tx) error {
			if _, err := tx.Enqueue(p.Conv, msgs); err != nil {
				return err
			}
			return e.saveCLI(tx, r.ID, p)
		})
		if err != nil {
			return CLIResult{}, err
		}
		e.wakeSender()
	}
	if p.Stage == cliMoving {
		if err := e.cliAwait(ctx, cliKey(r.ID, "moved")+":", cliMovedWait); err != nil {
			return CLIResult{}, err
		}
		if res, err := e.cliRebind(ctx, r, p, control, label, cwd); err != nil || res != nil {
			return derefResult(res), err
		}
	}
	if p.Stage == cliImporting {
		if err := e.cliAwaitImport(ctx, p.Conv, p.Import); err != nil {
			return CLIResult{}, err
		}
		err := e.update(func(tx *store.Tx) error {
			if err := e.cliAnnounce(tx, r.ID, p.Conv, control, label, cwd); err != nil {
				return err
			}
			p.Stage = ""
			return e.saveCLI(tx, r.ID, p)
		})
		if err != nil {
			return CLIResult{}, err
		}
		e.wakeSender()
	}
	what := "Teams control chat recreated"
	if !control {
		what = "Teams work chat recreated"
	}
	lines := []string{fmt.Sprintf("%s: %s", what, firstNonEmpty(p.URL, p.Chat))}
	if p.Title != "" {
		lines = append(lines, "Title: "+p.Title)
	}
	lines = append(lines, "Chat ID: "+p.Chat)
	if !control {
		lines = append(lines, "Session: "+label)
	}
	if p.Old != "" {
		lines = append(lines, "Previous Chat ID: "+p.Old)
	}
	if control {
		lines = append(lines, "The running Teams helper now uses the new control chat.")
	} else {
		lines = append(lines, "The running Teams helper now uses the new work chat.")
	}
	return CLIResult{Lines: lines}, nil
}

func derefResult(r *CLIResult) CLIResult {
	if r == nil {
		return CLIResult{}
	}
	return *r
}

// cliCreateChat creates the new chat (idempotent per key) under the
// account's write pacing, retrying a transient failure until ctx ends. A
// permanent refusal is the request's result.
func (e *Engine) cliCreateChat(ctx context.Context, title, key string) (channel.ChatInfo, *CLIResult, error) {
	for n := 0; ; n++ {
		if err := e.waitWrite(ctx); err != nil {
			return channel.ChatInfo{}, nil, ErrCLIRetry
		}
		started := e.now()
		info, err := e.ch.CreateChat(ctx, title, key)
		if err == nil {
			return info, nil, nil
		}
		if ctx.Err() != nil {
			return channel.ChatInfo{}, nil, ErrCLIRetry
		}
		var rej *channel.Rejected
		if errors.As(err, &rej) && rej.Permanent {
			return channel.ChatInfo{}, &CLIResult{Error: fmt.Sprintf("create the new Teams chat: %v", err)}, nil
		}
		wait := min(e.t.Hot<<min(n+1, 8), e.t.MaxBackoff)
		if th, ok := channel.AsThrottled(err); ok {
			wait = e.retryAfter(th)
			if th.Scope == channel.ScopeAccount || th.Scope == channel.ScopeUnknown {
				until := e.now().Add(wait)
				e.setGate(e.gWrite, until, "create chat throttled")
				e.paceThrottled(started, until)
			}
		}
		e.logf("recreate: create chat: %v; retry in %s", err, wait)
		if err := e.cliSleep(ctx, wait); err != nil {
			return channel.ChatInfo{}, nil, err
		}
	}
}

// cliAwait waits until no outbox row under prefix is pending, at most for
// bound (0: no bound).
func (e *Engine) cliAwait(ctx context.Context, prefix string, bound time.Duration) error {
	deadline := e.now().Add(bound)
	for {
		rows, err := e.st.OutboxByKeyPrefix(prefix)
		if err != nil {
			return err
		}
		pending := false
		for _, o := range rows {
			if o.State != store.OutSent && o.State != store.OutDropped {
				pending = true
			}
		}
		if !pending || (bound > 0 && !e.now().Before(deadline)) {
			return nil
		}
		if err := e.cliSleep(ctx, e.t.Tick); err != nil {
			return err
		}
	}
}

// cliClaim keeps the receiver and the sender off a conversation (as a
// read and a send in progress do) while its chat is switched.
func (e *Engine) cliClaim(ctx context.Context, cs *convState) (release func(), err error) {
	for {
		e.mu.Lock()
		if !cs.reading && !cs.sending {
			cs.reading, cs.sending = true, true
			e.mu.Unlock()
			return func() {
				e.mu.Lock()
				cs.reading, cs.sending = false, false
				e.mu.Unlock()
				e.wakeReader()
				e.wakeSender()
			}, nil
		}
		e.mu.Unlock()
		if err := e.cliSleep(ctx, e.t.Tick); err != nil {
			return nil, err
		}
	}
}

// cliRebind switches the conversation to the new chat in one transaction:
// the chat and a fresh receive cursor, a parked chat woken, a held one
// reactivated (--activate), the old chat's link given up when it could not
// be sent in time (it must not land in the new chat), and then either the
// history import or the announcements.
func (e *Engine) cliRebind(ctx context.Context, r CLIRequest, p *cliProgress, control bool, label, cwd string) (*CLIResult, error) {
	cs := e.conv(p.Conv)
	release, err := e.cliClaim(ctx, cs)
	if err != nil {
		return nil, err
	}
	defer release()
	// Read before the transaction: with the single connection of a
	// network filesystem a store read inside it waits forever.
	var src store.TranscriptSource
	var haveSrc bool
	var title string
	if r.History && !control {
		if src, haveSrc = e.cliSource(p.Conv, cs.threadID); haveSrc {
			title = e.sessionTitleOf(src.Path, src.ThreadID)
		}
	}
	var queued bool
	var gone string
	err = e.update(func(tx *store.Tx) error {
		queued, gone = false, ""
		c, ok, err := tx.Conversation(p.Conv)
		if err != nil {
			return err
		}
		if !ok || c.State == store.ConvClosed || c.State == store.ConvCreating {
			gone = fmt.Sprintf("Teams session %s was closed while its chat was recreated; the new chat %s is not used", label, firstNonEmpty(p.URL, p.Chat))
			return nil
		}
		rows, err := tx.PendingOutbox(p.Conv)
		if err != nil {
			return err
		}
		for _, o := range rows {
			if strings.HasPrefix(o.DeliveryKey, cliKey(r.ID, "moved")+":") {
				if err := tx.Drop(o.ID, "the chat was recreated before this link was confirmed"); err != nil {
					return err
				}
			}
		}
		if err := tx.SetChat(p.Conv, p.Chat, p.URL); err != nil {
			return err
		}
		key := store.ChatStreamKey(e.cfg.ChannelName, p.Chat)
		if _, ok, err := tx.Stream(key); err != nil {
			return err
		} else if !ok {
			if _, err := tx.AdmitWindow(key, p.Conv, nil, ""); err != nil {
				return err
			}
		}
		switch {
		case c.State == store.ConvParked:
			if err := tx.Wake(p.Conv); err != nil {
				return err
			}
		case c.State == store.ConvHold && r.Activate:
			if err := tx.Reactivate(p.Conv); err != nil {
				return err
			}
		}
		if r.History && !control {
			if haveSrc {
				ns, _, err := tx.Meta(mirrorNSKey(src.ID))
				if err != nil {
					return err
				}
				// The new chat has none of the session's messages: the
				// whole rollout, helper-run turns included, under keys of
				// its own (the old chat's keys are taken).
				job := importJob{Conv: p.Conv, Kind: importFull, Thread: src.ThreadID, Path: src.Path,
					Rewind: true, KeepTeams: true, NS: firstNonEmpty(ns, src.ThreadID) + "@r" + r.ID}
				id, err := e.queueImport(tx, job)
				if err != nil && !errors.Is(err, errImportRunning) {
					return err
				}
				if err == nil {
					if err := e.enqueueNotice(tx, p.Conv, fmt.Sprintf("import:%d:title", id), textImportTitle(title)); err != nil {
						return err
					}
					p.Import, queued = id, true
				}
			}
		}
		if queued {
			p.Stage = cliImporting
		} else {
			if err := e.cliAnnounce(tx, r.ID, p.Conv, control, label, cwd); err != nil {
				return err
			}
			p.Stage = ""
		}
		if err := e.saveCLI(tx, r.ID, p); err != nil {
			return err
		}
		_, err = e.refresh(tx, p.Conv)
		return err
	})
	if err != nil {
		return nil, err
	}
	if gone != "" {
		return &CLIResult{Error: gone}, nil
	}
	now := e.now()
	e.mu.Lock()
	cs.cursor, cs.seeded = "", true
	cs.scanLast, cs.ownPosts, cs.scanDue, cs.scanLive = "", nil, false, 0
	cs.failures, cs.nextRead, cs.lastActivity, cs.lastUser = 0, now, now, now
	e.mu.Unlock()
	if queued {
		e.importQueued(p.Conv)
	}
	return nil, nil
}

// cliAnnounce queues the new chat's @mention and ready message (v0.1.20:
// "Control chat recreated." and the control help, or the work chat's
// lifecycle notice and ready anchor).
func (e *Engine) cliAnnounce(tx *store.Tx, id string, conv int64, control bool, label, cwd string) error {
	text, ready := "Control chat recreated.", "control chat is ready.\n\n"+controlHelpText
	if !control {
		text, ready = textWorkChatRecreated(label, cwd), textWorkChatReady(label, cwd)
	}
	msgs, err := e.render(context.Background(), channel.RichDoc{Label: labelHelper, Markdown: text, Mention: true}, store.OutNotice, cliKey(id, "recreated"))
	if err != nil {
		return err
	}
	if _, err := tx.Enqueue(conv, msgs); err != nil {
		return err
	}
	return e.enqueueNotice(tx, conv, cliKey(id, "ready"), ready)
}

// cliAwaitImport waits until the import job id of conv is finished.
func (e *Engine) cliAwaitImport(ctx context.Context, conv, id int64) error {
	for {
		j, ok := e.importJobOf(conv)
		if !ok || j.ID != id {
			return nil
		}
		if err := e.cliSleep(ctx, e.t.Tick); err != nil {
			return err
		}
	}
}

// ---- publish-history ----

// cliPublishHistory publishes the complete local history of a session to
// its chat (v0.1.20 PublishSessionFullHistory): `helper publish-history
// full` from the command line. Without --force it posts only what the chat
// is missing; --force replays everything under fresh delivery keys.
func (e *Engine) cliPublishHistory(ctx context.Context, r CLIRequest, p *cliProgress) (CLIResult, error) {
	if p.Stage == "" {
		cs, msg := e.cliSession(r.Selector)
		if cs == nil {
			return cliFail("%s", msg)
		}
		e.mu.Lock()
		id, label, state, chat, thread := cs.id, cs.label, cs.state, cs.chat, cs.threadID
		e.mu.Unlock()
		switch {
		case state != store.ConvActive && state != store.ConvParked:
			return cliFail("Teams session %s has status %q; history is published only to an open work chat", label, state)
		case chat == "":
			return cliFail("Teams session %s has no Teams chat yet", label)
		}
		src, ok := e.cliSource(id, thread)
		if !ok {
			return cliFail("local Codex transcript not found for session %s", label)
		}
		if _, running := e.importJobOf(id); running {
			return cliFail("a history import is still running for session %s; wait for `Import complete` and retry", label)
		}
		info, err := e.statFile(src.Path)
		if err != nil {
			return cliFail("local Codex transcript not found for session %s", label)
		}
		if !r.Force {
			if v, _, err := e.st.Meta(fullHistKey(id)); err == nil && v == "1" && src.Offset >= info.Size {
				return CLIResult{Lines: []string{"Full local Codex history is already published to this Teams chat."}}, nil
			}
		}
		title := e.sessionTitleOf(src.Path, src.ThreadID) // reads the store: not inside the transaction
		running := false
		err = e.update(func(tx *store.Tx) error {
			running = false
			ns, _, err := tx.Meta(mirrorNSKey(src.ID))
			if err != nil {
				return err
			}
			job := importJob{Conv: id, Kind: importFull, Thread: src.ThreadID, Path: src.Path, Rewind: true, NS: ns}
			if r.Force {
				// v0.1.20's fresh replay namespace: everything is posted
				// again, helper-run turns included.
				job.NS, job.KeepTeams = firstNonEmpty(ns, src.ThreadID)+"@f"+r.ID, true
			}
			jid, err := e.queueImport(tx, job)
			if errors.Is(err, errImportRunning) {
				running = true
				return nil
			}
			if err != nil {
				return err
			}
			if err := e.enqueueNotice(tx, id, fmt.Sprintf("import:%d:title", jid), textImportTitle(title)); err != nil {
				return err
			}
			p.Conv, p.Import, p.Stage = id, jid, cliImporting
			return e.saveCLI(tx, r.ID, p)
		})
		if err != nil {
			return CLIResult{}, err
		}
		if running {
			return cliFail("a history import is still running for session %s; wait for `Import complete` and retry", label)
		}
		e.importQueued(id)
		e.wakeSender()
	}
	if err := e.cliAwaitImport(ctx, p.Conv, p.Import); err != nil {
		return CLIResult{}, err
	}
	return CLIResult{Lines: []string{"Full local Codex history published to the selected Teams chat."}}, nil
}

// ---- send-file ----

// cliSendFile sends a file the command staged to a work chat (v0.1.20
// `teams send-file`), through the same staging and resumable upload as
// `helper file`, and waits until it is posted.
func (e *Engine) cliSendFile(ctx context.Context, r CLIRequest, p *cliProgress) (CLIResult, error) {
	if p.Stage == "" {
		var cs *convState
		if chat := strings.TrimSpace(r.ChatID); chat != "" {
			e.mu.Lock()
			if id, ok := e.byChat[chat]; ok && id != e.inboxID {
				cs = e.convs[id]
			}
			e.mu.Unlock()
			if cs == nil {
				return cliFail("Teams chat %s is not a chat of this helper; choose a target with --session", chat)
			}
		} else {
			e.mu.Lock()
			for id, c := range e.convs {
				if c.kind == store.KindWork && id != e.inboxID && c.label == strings.TrimSpace(r.Selector) &&
					(cs == nil || cs.state == store.ConvClosed) {
					cs = c
				}
			}
			e.mu.Unlock()
			if cs == nil {
				return cliFail("Teams session not found: %s", strings.TrimSpace(r.Selector))
			}
		}
		e.mu.Lock()
		id, label, state, chat := cs.id, cs.label, cs.state, cs.chat
		e.mu.Unlock()
		switch {
		case state == store.ConvClosed:
			return cliFail("Teams session %s is closed", label)
		case chat == "":
			return cliFail("Teams session %s has no Teams chat yet", label)
		case e.cfg.FilesDir == "":
			return cliFail("Teams file upload is not available in this helper")
		}
		name := safeName(filepath.Base(r.File))
		staged := filepath.Join(e.cfg.FilesDir, "send", "cli", r.ID, name)
		size, err := snapshot(r.File, staged)
		if err != nil {
			return cliFail("Teams file upload rejected: %s: %v", name, err)
		}
		err = e.update(func(tx *store.Tx) error {
			if msg := strings.TrimSpace(r.Message); msg != "" {
				if err := e.enqueueNotice(tx, id, cliKey(r.ID, "message"), msg); err != nil {
					return err
				}
			}
			if _, err := tx.Enqueue(id, []store.OutMsg{{DeliveryKey: cliKey(r.ID, "file"), Kind: store.OutControl,
				File: &store.OutFile{LocalPath: staged, Size: size}}}); err != nil {
				return err
			}
			p.Conv, p.Name, p.Title, p.Stage = id, name, label, cliSending
			return e.saveCLI(tx, r.ID, p)
		})
		if err != nil {
			return CLIResult{}, err
		}
		e.wakeSender()
	}
	if err := e.cliAwait(ctx, cliKey(r.ID, "file"), 0); err != nil {
		return CLIResult{}, err
	}
	rows, err := e.st.OutboxByKeyPrefix(cliKey(r.ID, "file"))
	if err != nil {
		return CLIResult{}, err
	}
	for _, o := range rows {
		if o.DeliveryKey == cliKey(r.ID, "file") && o.State == store.OutSent {
			lines := []string{"Sent Teams file attachment: " + p.Name, "Target session: " + p.Title}
			if o.ExtMsgID != "" {
				lines = append(lines, "Teams message id: "+o.ExtMsgID)
			}
			return CLIResult{Lines: lines}, nil
		}
	}
	return cliFail("Teams file upload failed: %s could not be sent", p.Name)
}
