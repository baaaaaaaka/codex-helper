// Requests from the command line (gap batch G): `cxp teams control
// --recreate` (F-CTL-2), `cxp teams chat recreate` (F-WRK-9), `cxp teams
// chat publish-history` (F-MIR-6) and `cxp teams send-file` (F-RND-10).
// A command never writes the store a running helper holds: it leaves a
// request next to the store and the helper hands it to CLIRequest.
//
// A request runs once per id. Every step is keyed by the id (the chat
// creation key, the delivery keys, the progress kept in meta), so a request
// delivered again after a restart resumes where it stopped and returns the
// saved result once it is done.

// CLI request operations.
const (
	CLIRecreateControl = "recreate-control"
	CLIRecreateChat    = "recreate-chat"
	CLIPublishHistory  = "publish-history"
	CLISendFile        = "send-file"
)

// CLIRequest is one command-line request.
type CLIRequest struct {
	ID       string `json:"id"`
	Op       string `json:"op"`
	Selector string `json:"selector,omitempty"` // session id, Codex thread id, Teams chat id or its 12-character prefix
	ChatID   string `json:"chat_id,omitempty"`  // send-file --chat-id
	History  bool   `json:"history,omitempty"`  // recreate: publish the full local history into the new chat
	Activate bool   `json:"activate,omitempty"` // recreate: reactivate a held session
	Force    bool   `json:"force,omitempty"`    // publish-history: replay into a fresh namespace
	File     string `json:"file,omitempty"`     // send-file: the file the command staged
	Message  string `json:"message,omitempty"`  // send-file: text posted with the file
}

// CLIResult is what the command prints: Lines on success, Error otherwise.
type CLIResult struct {
	Lines []string `json:"lines,omitempty"`
	Error string   `json:"error,omitempty"`
}

// ErrCLIRetry: the request was not finished (the engine is not ready or is
// stopping); hand it in again later.
var ErrCLIRetry = errors.New("engine: request not finished; retry later")

const metaCLIPrefix = "engine_cli:" // + request id: cliProgress

// cliMovedWait bounds the wait for the "chat moved" link in the old chat
// before the chat is switched anyway (the old chat may be the broken one).
var cliMovedWait = 2 * time.Minute

// Progress stages of a request.
const (
	cliCreated   = "created"   // the new chat exists
	cliMoving    = "moving"    // the link to it is queued in the old chat
	cliImporting = "importing" // switched; the history import runs
	cliSending   = "sending"   // send-file: the file is queued
)

type cliProgress struct {
	Stage  string     `json:"stage,omitempty"`
	Conv   int64      `json:"conv,omitempty"`
	Old    string     `json:"old,omitempty"`
	Chat   string     `json:"chat,omitempty"`
	URL    string     `json:"url,omitempty"`
	Title  string     `json:"title,omitempty"`
	Name   string     `json:"name,omitempty"`
	Import int64      `json:"import,omitempty"`
	Result *CLIResult `json:"result,omitempty"`
}

// cliState runs one request at a time.
type cliState struct {
	mu   sync.Mutex
	busy bool
}

func cliKey(id, step string) string { return "cli:" + id + ":" + step }

// validCLIID: ids are generated by the command ([0-9a-z-], at most 64).
func validCLIID(id string) bool {
	if id == "" || len(id) > 64 {
		return false
	}
	for _, r := range id {
		if !(r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r == '-') {
			return false
		}
	}
	return true
}

// CLIRequest runs a command-line request and returns what the command
// prints. It blocks until the request is done; ErrCLIRetry (or a store
// error) means it is not, and must be handed in again later.
func (e *Engine) CLIRequest(ctx context.Context, r CLIRequest) (CLIResult, error) {
	if !validCLIID(r.ID) {
		return CLIResult{Error: "invalid request id"}, nil
	}
	if !e.cliReady() {
		return CLIResult{}, ErrCLIRetry
	}
	for {
		e.cli.mu.Lock()
		if !e.cli.busy {
			e.cli.busy = true
			e.cli.mu.Unlock()
			break
		}
		e.cli.mu.Unlock()
		if err := e.cliSleep(ctx, e.t.Tick); err != nil {
			return CLIResult{}, err
		}
	}
	defer func() {
		e.cli.mu.Lock()
		e.cli.busy = false
		e.cli.mu.Unlock()
	}()
	var p cliProgress
	if v, ok, err := e.st.Meta(metaCLIPrefix + r.ID); err != nil {
		return CLIResult{}, err
	} else if ok && v != "" {
		if err := json.Unmarshal([]byte(v), &p); err != nil {
			return CLIResult{}, fmt.Errorf("request %s: %w", r.ID, err)
		}
	}
	if p.Result != nil {
		return *p.Result, nil
	}
	var (
		res CLIResult
		err error
	)
	switch r.Op {
	case CLIRecreateControl:
		res, err = e.cliRecreate(ctx, r, &p, true)
	case CLIRecreateChat:
		res, err = e.cliRecreate(ctx, r, &p, false)
	case CLIPublishHistory:
		res, err = e.cliPublishHistory(ctx, r, &p)
	case CLISendFile:
		res, err = e.cliSendFile(ctx, r, &p)
	default:
		res = CLIResult{Error: fmt.Sprintf("unknown request %q (this helper version does not handle it)", r.Op)}
	}
	if err != nil {
		if ctx.Err() != nil {
			return CLIResult{}, ErrCLIRetry
		}
		return CLIResult{}, err
	}
	p.Result = &res
	if err := e.update(func(tx *store.Tx) error { return e.saveCLI(tx, r.ID, &p) }); err != nil {
		return CLIResult{}, err
	}
	return res, nil
}

func (e *Engine) cliReady() bool {
	if e.stopping.Load() {
		return false
	}
	e.mu.Lock()
	defer e.mu.Unlock()
	ctl := e.convs[e.controlID]
	return e.controlID != 0 && ctl != nil && ctl.chat != ""
}

func (e *Engine) saveCLI(tx *store.Tx, id string, p *cliProgress) error {
	b, err := json.Marshal(p)
	if err != nil {
		return err
	}
	return tx.SetMeta(metaCLIPrefix+id, string(b))
}

func (e *Engine) cliSleep(ctx context.Context, d time.Duration) error {
	t := time.NewTimer(d)
	defer t.Stop()
	select {
	case <-ctx.Done():
		return ErrCLIRetry
	case <-t.C:
		return nil
	}
}

func cliFail(format string, args ...any) (CLIResult, error) {
	return CLIResult{Error: fmt.Sprintf(format, args...)}, nil
}

// cliSession resolves a work session as v0.1.20's recreate selector did:
// session id, Codex thread id, Teams chat id, then a 12-character chat id
// prefix. An open session wins over a closed one.
func (e *Engine) cliSession(sel string) (*convState, string) {
	sel = strings.TrimSpace(sel)
	if sel == "" {
		return nil, "session id, Codex thread id, or Teams chat id is required"
	}
	e.mu.Lock()
	defer e.mu.Unlock()
	match := []func(cs *convState) bool{
		func(cs *convState) bool { return cs.label == sel },
		func(cs *convState) bool { return cs.threadID != "" && cs.threadID == sel },
		func(cs *convState) bool { return cs.chat != "" && cs.chat == sel },
		func(cs *convState) bool { return cs.chat != "" && strings.EqualFold(shortChatID(cs.chat), sel) },
	}
	for _, m := range match {
		var hit *convState
		for id, cs := range e.convs {
			if cs.kind != store.KindWork || id == e.inboxID || !m(cs) {
				continue
			}
			if hit == nil || (hit.state == store.ConvClosed && cs.state != store.ConvClosed) ||
				((hit.state == store.ConvClosed) == (cs.state == store.ConvClosed) && cs.id > hit.id) {
				hit = cs
			}
		}
		if hit != nil {
			return hit, ""
		}
	}
	return nil, fmt.Sprintf("Teams session not found for %q", sel)
}

func shortChatID(id string) string {
	id = strings.TrimSpace(id)
	if len(id) <= 12 {
		return id
	}
	return id[:12]
}

// cliSource is the transcript source linked to a work conversation.
func (e *Engine) cliSource(conv int64, thread string) (store.TranscriptSource, bool) {
	srcs, err := e.st.Sources()
	if err != nil {
		return store.TranscriptSource{}, false
	}
	var src store.TranscriptSource
	found := false
	for _, s := range srcs {
		if s.ConvID == conv && s.State == store.SrcTracking && (thread == "" || s.ThreadID == thread) {
			src, found = s, true
		}
	}
	return src, found
}

// textChatMoved is v0.1.20's link in the old chat
// (recreatedChatMovedNoticeText).
func textChatMoved(label, session, url string) string {
	target := "the new " + label
	if session != "" {
		target += " for " + session
	}
	lines := []string{"🔁 This chat moved", "", "Open " + target + ":"}
	if url = strings.TrimSpace(url); url != "" {
		lines = append(lines, url)
	}
	return strings.Join(append(lines, "", "Messages here may not be handled after the switch."), "\n")
}

// textWorkChatRecreated is v0.1.20's workChatLifecycleNotice("Work chat
// recreated", session).
func textWorkChatRecreated(label, cwd string) string {
	text := "Work chat recreated: " + label + "."
	if cwd = strings.TrimSpace(cwd); cwd != "" {
		text += "\nWorking directory: " + cwd
	}
	return text
}

